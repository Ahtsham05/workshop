/**
 * Master registry of every "quick-link-able" action in the system — the single source
 * of truth behind both the customizable Quick Links dashboard panel and the voice
 * command matcher. Mirrors the full app navigation (client/src/components/layout/data/
 * sidebar-data.ts) so the "Available actions" picker covers everything the sidebar
 * does; a new feature registers itself by adding one object here instead of touching
 * quickLinks model/service/controller code.
 *
 * A brand-new user's Quick Links are NOT seeded with everything (that would be
 * useless) — only the curated, ordered subset named in DEFAULT_ACTION_KEY_ORDER below.
 * Everything else is still fully browsable/pinnable via the picker and reachable by
 * voice command.
 *
 * - `iconKey` must have a matching entry in client/src/lib/quick-link-icons.ts's ICON_MAP
 *   (tabler `Icon*` names and plain lucide names are both supported there, matching
 *   whichever library sidebar-data.ts itself uses for that same nav item).
 * - `color` is a Tailwind bg/hover pair, same convention as the old hardcoded
 *   dashboard/components/quick-actions.tsx this feature replaces.
 * - `permission`/`anyPermission` keys must exist in permission-registry.js.
 * - `businessTypes`/`excludeBusinessTypes` — allow-list / deny-list of Organization
 *   business types, mirroring sidebar-data.ts's own fields of the same name.
 * - `systemRole` — allow-list of User.systemRole values (platform-level admin pages).
 * - `allowedSchoolRoles`/`excludedSchoolRoles` — allow/deny by User.schoolRole (school
 *   portals: 'teacher' vs everyone else).
 * - `allowedEmails` — allow-list by exact User.email (mirrors one hardcoded sidebar
 *   entry gated the same way).
 * - `synonyms` are extra spoken phrases the voice command matcher should also accept
 *   besides the label itself.
 */

