import { PRINT_LANGUAGES, type PrintLanguage } from '@/lib/native-language'

/** Print heading languages: English plus each native language with hand-written headings. */
export type InvoiceLanguage = PrintLanguage

export interface InvoiceLanguageContext {
  language?: InvoiceLanguage
  isUrduOnly?: boolean
  userPreferredLanguage?: InvoiceLanguage
}

export const resolveInvoiceLanguage = ({
  language,
  isUrduOnly,
  userPreferredLanguage,
}: InvoiceLanguageContext): InvoiceLanguage => {
  if (isUrduOnly) return 'ur'
  return toPrintLanguage(language ?? userPreferredLanguage)
}

/** Any UI/app language → a print language with headings, English when it has none. */
export const toPrintLanguage = (value: string | null | undefined): InvoiceLanguage =>
  (PRINT_LANGUAGES as readonly string[]).includes(String(value)) ? (value as InvoiceLanguage) : 'en'

